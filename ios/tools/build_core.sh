#!/bin/sh
# Builds ios/build/OnAirCore.xcframework for the device and the simulator. Needs: Xcode, cmake, ninja, pkg-config, rustup with the
# aarch64-apple-ios and aarch64-apple-ios-sim targets, and the headers of `brew install hackrf libusb ffmpeg` (only the headers are used).
# Usage: build_core.sh [iphoneos] [iphonesimulator]   (default: both)
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$ROOT/ios/build"
SDKS=${*:-iphoneos iphonesimulator}
LIBIIO_TAG=v0.26   # the desktop driver refuses libiio 1.x
ARGS=""
for sdk in $SDKS; do
  B="$OUT/$sdk"
  "$ROOT/ios/tools/build_ffmpeg.sh" "$sdk"
  "$ROOT/ios/tools/build_codecs.sh" "$sdk"
  # libiio, unchanged from upstream: network backend only, using the SDK's libxml2. The core finds it by name (DynLib, native_common.h).
  [ -d "$OUT/deps/libiio" ] || git clone -q --depth 1 --branch "$LIBIIO_TAG" https://github.com/analogdevicesinc/libiio.git "$OUT/deps/libiio"
  SDKPATH=$(xcrun --sdk "$sdk" --show-sdk-path)
  cmake -S "$OUT/deps/libiio" -B "$B/libiio" -G Ninja \
    -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT="$sdk" -DCMAKE_OSX_ARCHITECTURES=arm64 -DCMAKE_OSX_DEPLOYMENT_TARGET=17.0 \
    -DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY -DCMAKE_BUILD_TYPE=Release \
    -DBUILD_SHARED_LIBS=OFF -DOSX_FRAMEWORK=OFF -DOSX_PACKAGE=OFF -DWITH_TESTS=OFF -DWITH_IIOD=OFF -DWITH_LOCAL_BACKEND=OFF \
    -DWITH_USB_BACKEND=OFF -DWITH_SERIAL_BACKEND=OFF -DHAVE_DNS_SD=OFF -DWITH_NETWORK_BACKEND=ON -DWITH_XML_BACKEND=ON \
    -DLIBXML2_INCLUDE_DIR="$SDKPATH/usr/include/libxml2" -DLIBXML2_LIBRARIES=xml2
  cmake --build "$B/libiio"
  # The core looks libiio's functions up by name (DynLib, native_common.h): generate that table from what the library exports
  { echo '/* generated by build_core.sh */'
    echo '#include <string.h>'
    syms=$(nm -gU "$B/libiio/libiio.a" 2>/dev/null | awk '$3 ~ /^_iio_/ {print substr($3, 2)}' | sort -u)
    for f in $syms; do echo "extern char $f;"; done
    echo 'void* onair_linked_symbol(const char* name) {'
    for f in $syms; do echo "  if (!strcmp(name, \"$f\")) return &$f;"; done
    echo '  return NULL;'
    echo '}'
  } > "$B/iio_symbols.c"
  cmake -S "$ROOT/ios/core" -B "$B" -G Ninja \
    -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT="$sdk" -DCMAKE_OSX_ARCHITECTURES=arm64 -DCMAKE_OSX_DEPLOYMENT_TARGET=17.0 \
    -DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY -DCMAKE_BUILD_TYPE=Release -DONAIR_IIO_SYMBOLS="$B/iio_symbols.c" -DDECT2_FFMPEG_PREFIX="$B/ffmpeg"
  cmake --build "$B" --target onair_ios
  # codec2 stays a library of its own, signed into the app with the plug-ins
  cp -L "$B/libcodec2.1.2.dylib" "$B/codecs/"
  # one archive for Xcode: every static library of the build, Rust included
  mkdir -p "$B/merged"
  find "$B" -name '*.a' -not -path '*/merged/*' -not -path '*/deps/*' -not -path '*/ffmpeg-build/*' | sort > "$B/merged/libs.txt"
  xcrun libtool -static -no_warning_for_no_symbols -o "$B/merged/libOnAirCore.a" -filelist "$B/merged/libs.txt" 2>/dev/null
  ARGS="$ARGS -library $B/merged/libOnAirCore.a -headers $ROOT/ios/core/include"
done
rm -rf "$OUT/OnAirCore.xcframework"
xcodebuild -create-xcframework $ARGS -output "$OUT/OnAirCore.xcframework"
